"""Generate the Dart port's character tables and its parity fixture from the Python original.

The app searches the `normalized_text` columns of content.sqlite, which the data
pipeline wrote with `shatibiyyah.arabic.normalize.normalize_matching`. The Dart
`Normalizer` must turn a typed query into exactly the same form, so its
character classes are generated from the Python module, never copied by hand.

Run with the data platform's interpreter:

    ../../shatibiyyah-data/.venv/bin/python tool/gen_normalizer.py

Writes lib/domain/normalizer_tables.dart and test/fixtures/normalizer_parity.json.
"""

from __future__ import annotations

import json
import re
import sqlite3
import sys
import unicodedata
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
DATA = APP.parents[1] / "shatibiyyah-data"
sys.path.insert(0, str(DATA / "src"))

from shatibiyyah.arabic import normalize as n  # noqa: E402

# Ranges where NFKC changes text a user could type or paste into a search box:
# Arabic presentation forms A and B, and full-/half-width forms.
NFKC_RANGES = [(0xFB50, 0xFDFF), (0xFE70, 0xFEFF), (0xFF00, 0xFFEF)]


def dart_string(text: str) -> str:
    return "'" + "".join(f"\\u{{{ord(c):X}}}" for c in text) + "'"


def code_set(chars: str) -> str:
    return "{" + ", ".join(f"0x{ord(c):04X}" for c in sorted(set(chars))) + "}"


def tables() -> str:
    nfkc = {}
    for lo, hi in NFKC_RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            mapped = unicodedata.normalize("NFKC", ch)
            if mapped != ch and unicodedata.category(ch) != "Cn":
                nfkc[cp] = mapped
    whitespace = "".join(chr(cp) for cp in range(0x10000) if n._WS_RE.fullmatch(chr(cp)))
    lines = [
        "// GENERATED by tool/gen_normalizer.py from shatibiyyah-data's",
        f"// shatibiyyah.arabic.normalize (NORMALIZER_VERSION {n.NORMALIZER_VERSION}). Do not edit by hand.",
        "",
        f"const String kNormalizerVersion = '{n.NORMALIZER_VERSION}';",
        "",
        "/// NFKC of single characters in the presentation-form and width-form ranges.",
        "const Map<int, String> kNfkc = {",
        *[f"  0x{cp:04X}: {dart_string(v)}," for cp, v in sorted(nfkc.items())],
        "};",
        "",
        f"const Set<int> kInvisibles = {code_set(n.INVISIBLES)};",
        f"const int kTatweel = 0x{ord(n.TATWEEL):04X};",
        f"const Set<int> kMarks = {code_set(n.TASHKEEL + n.QURANIC_MARKS)};",
        "const Map<int, int> kFolds = {",
        *[f"  0x{cp:04X}: 0x{ord(v):04X}," for cp, v in sorted(n._MATCHING_TABLE.items())],
        "};",
        f"const Set<int> kToSpace = {code_set(n._STRIP_CHARS_MATCHING)};",
        f"const Set<int> kWhitespace = {code_set(whitespace)};",
        "",
    ]
    return "\n".join(lines)


def fixture() -> list[list[str]]:
    """(input, expected) pairs: every verse, a spread of segments and footnotes, and edge cases."""
    db = sqlite3.connect(f"file:{DATA / 'data' / 'database.sqlite'}?mode=ro", uri=True)
    cases: list[list[str]] = []
    for (text,) in db.execute("SELECT full_text FROM matn_verses ORDER BY verse_number"):
        cases.append([text, n.normalize_matching(text)])
    # 500 segments spread evenly over all three books, truncated so the fixture
    # stays small; the expected value is computed on the truncation.
    rows = db.execute("SELECT display_text FROM commentary_segments ORDER BY id").fetchall()
    for (text,) in rows[:: max(1, len(rows) // 500)][:500]:
        cases.append([text[:300], n.normalize_matching(text[:300])])
    for (text,) in db.execute("SELECT display_text FROM footnotes ORDER BY id LIMIT 200"):
        cases.append([text, n.normalize_matching(text)])
    for text in [
        "ﻻ إله إلا الله", "ﷲ", "ﺑﺴﻢ", "بَدَأْتُ", "  ورْش‏ ", "«النَّقْل»، (حمزة)!", "ﻋﻠﻰ", "مَكَّة", "١٢٣",
        "Ｗａｒｓｈ", "قـــال", "سُؤَال رَئِيس", "ی ک", "  مد　",
    ]:
        cases.append([text, n.normalize_matching(text)])
    return cases


def main() -> None:
    out = APP / "lib" / "domain" / "normalizer_tables.dart"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(tables(), encoding="utf-8")
    fx = APP / "test" / "fixtures" / "normalizer_parity.json"
    fx.parent.mkdir(parents=True, exist_ok=True)
    cases = fixture()
    fx.write_text(json.dumps({"normalizer_version": n.NORMALIZER_VERSION, "cases": cases},
                             ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"wrote {out.relative_to(APP)} and {fx.relative_to(APP)} ({len(cases)} cases)")


if __name__ == "__main__":
    main()
